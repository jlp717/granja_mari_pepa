async function main() {
  const connection = await odbc.connect(connectionString);
  try {
    const existing = await connection.query(
      "SELECT TRIM(TABLE_NAME) AS NAME FROM QSYS2.SYSTABLES WHERE TABLE_SCHEMA = 'JAVIER'",
    );
    const have = new Set(existing.map((row) => String(row.NAME).trim()));
    for (const [name, ddl] of Object.entries(TABLES)) {
      if (have.has(name)) {
        console.log('SKIP', name);
        continue;
      }
      await connection.query(ddl);
      console.log('CREATED', name);
    }

    const pdfColumn = await connection.query(
      "SELECT COLUMN_NAME FROM QSYS2.SYSCOLUMNS WHERE TABLE_SCHEMA='JAVIER' AND TABLE_NAME='ADMIN_MAGAZINES' AND COLUMN_NAME='PDF_DATA'",
    );
    if (!pdfColumn.length) {
      await connection.query(
        'ALTER TABLE JAVIER.ADMIN_MAGAZINES ADD COLUMN PDF_DATA BLOB(50M)',
      );
      console.log('MIGRATED ADMIN_MAGAZINES.PDF_DATA');
    }
  } finally {
    await connection.close();
  }
}

main()
  .then(() => process.exit(0))
  .catch((error) => {
    console.error('ERROR', error.message || error);
    process.exit(1);
  });
