/**
 * Test líneas negativas
 */
const db = require('../app/config/odbcConfig');

(async () => {
  await db.initialize();
  console.log('TEST LÍNEAS NEGATIVAS\n');

  const F = "'700', '701', '702', '703', '704', '705', '706'";
  const C = "'AB', 'RG', 'VT'";

  // Ver líneas con CANTIDADENVASES negativo o 0
  const neg = await db.query(`
    SELECT TRIM(LAC.TIPOVENTA) AS TV, TRIM(ART.CODIGOFAMILIA) AS FAM, 
           TRIM(LAC.CLASELINEA) AS CLAVE, COUNT(*) AS N, SUM(LAC.CANTIDADENVASES) AS CAJAS
    FROM DSEDAC.CAC CAC
    INNER JOIN DSEDAC.LAC LAC ON 
      LAC.SUBEMPRESAALBARAN = CAC.SUBEMPRESAALBARAN AND
      LAC.EJERCICIOALBARAN = CAC.EJERCICIOALBARAN AND
      LAC.SERIEALBARAN = CAC.SERIEALBARAN AND
      LAC.TERMINALALBARAN = CAC.TERMINALALBARAN AND
      LAC.NUMEROALBARAN = CAC.NUMEROALBARAN
    INNER JOIN DSEDAC.ART ART ON TRIM(LAC.CODIGOARTICULO) = TRIM(ART.CODIGOARTICULO)
    WHERE CAC.ANODOCUMENTO = 2026 AND CAC.MESDOCUMENTO = 4
      AND TRIM(CAC.CODIGOCLIENTEFACTURA) LIKE '43%'
      AND CAC.NUMEROFACTURA > 0
      AND TRIM(ART.CODIGOFAMILIA) IN (${F})
      AND TRIM(LAC.CLASELINEA) IN (${C})
      AND LAC.CANTIDADENVASES <= 0
    GROUP BY TRIM(LAC.TIPOVENTA), TRIM(ART.CODIGOFAMILIA), TRIM(LAC.CLASELINEA)
  `);
  
  console.log('Líneas con CANTIDADENVASES <= 0:');
  let negCC = 0, negSC = 0;
  neg.forEach(x => {
    console.log('  ' + x.TV + ' | ' + x.FAM + ' | ' + x.CLAVE + ': ' + x.N + ' líneas, ' + x.CAJAS + ' cajas');
    if(x.TV === 'CC') negCC += Number(x.CAJAS);
    if(x.TV === 'SC') negSC += Number(x.CAJAS);
  });
  console.log('Total negativo: CC=' + negCC + ', SC=' + negSC);

  // Mi query actual (con negatives)
  const r1 = await db.query(`
    SELECT TRIM(LAC.TIPOVENTA) AS TV, SUM(COALESCE(LAC.CANTIDADENVASES,0)) AS CAJAS
    FROM DSEDAC.CAC CAC
    INNER JOIN DSEDAC.LAC LAC ON 
      LAC.SUBEMPRESAALBARAN = CAC.SUBEMPRESAALBARAN AND
      LAC.EJERCICIOALBARAN = CAC.EJERCICIOALBARAN AND
      LAC.SERIEALBARAN = CAC.SERIEALBARAN AND
      LAC.TERMINALALBARAN = CAC.TERMINALALBARAN AND
      LAC.NUMEROALBARAN = CAC.NUMEROALBARAN
    INNER JOIN DSEDAC.ART ART ON TRIM(LAC.CODIGOARTICULO) = TRIM(ART.CODIGOARTICULO)
    WHERE CAC.ANODOCUMENTO = 2026 AND CAC.MESDOCUMENTO = 4
      AND TRIM(CAC.CODIGOCLIENTEFACTURA) LIKE '43%'
      AND CAC.NUMEROFACTURA > 0
      AND TRIM(ART.CODIGOFAMILIA) IN (${F})
      AND TRIM(LAC.CLASELINEA) IN (${C})
    GROUP BY TRIM(LAC.TIPOVENTA)
  `);
  let cc1=0, sc1=0; r1.forEach(x=>{if(x.TV==='CC')cc1=x.CAJAS;if(x.TV==='SC')sc1=x.CAJAS;});
  console.log('\nMi actual: CC=' + cc1 + ', SC=' + sc1);

  // Sumar solo positivos
  const r2 = await db.query(`
    SELECT TRIM(LAC.TIPOVENTA) AS TV, SUM(LAC.CANTIDADENVASES) AS CAJAS
    FROM DSEDAC.CAC CAC
    INNER JOIN DSEDAC.LAC LAC ON 
      LAC.SUBEMPRESAALBARAN = CAC.SUBEMPRESAALBARAN AND
      LAC.EJERCICIOALBARAN = CAC.EJERCICIOALBARAN AND
      LAC.SERIEALBARAN = CAC.SERIEALBARAN AND
      LAC.TERMINALALBARAN = CAC.TERMINALALBARAN AND
      LAC.NUMEROALBARAN = CAC.NUMEROALBARAN
    INNER JOIN DSEDAC.ART ART ON TRIM(LAC.CODIGOARTICULO) = TRIM(ART.CODIGOARTICULO)
    WHERE CAC.ANODOCUMENTO = 2026 AND CAC.MESDOCUMENTO = 4
      AND TRIM(CAC.CODIGOCLIENTEFACTURA) LIKE '43%'
      AND CAC.NUMEROFACTURA > 0
      AND TRIM(ART.CODIGOFAMILIA) IN (${F})
      AND TRIM(LAC.CLASELINEA) IN (${C})
      AND LAC.CANTIDADENVASES > 0
    GROUP BY TRIM(LAC.TIPOVENTA)
  `);
  let cc2=0, sc2=0; r2.forEach(x=>{if(x.TV==='CC')cc2=x.CAJAS;if(x.TV==='SC')sc2=x.CAJAS;});
  console.log('Solo positivos: CC=' + cc2 + ', SC=' + sc2);

  // Con ABS (valor absoluto)
  const r3 = await db.query(`
    SELECT TRIM(LAC.TIPOVENTA) AS TV, SUM(ABS(COALESCE(LAC.CANTIDADENVASES,0))) AS CAJAS
    FROM DSEDAC.CAC CAC
    INNER JOIN DSEDAC.LAC LAC ON 
      LAC.SUBEMPRESAALBARAN = CAC.SUBEMPRESAALBARAN AND
      LAC.EJERCICIOALBARAN = CAC.EJERCICIOALBARAN AND
      LAC.SERIEALBARAN = CAC.SERIEALBARAN AND
      LAC.TERMINALALBARAN = CAC.TERMINALALBARAN AND
      LAC.NUMEROALBARAN = CAC.NUMEROALBARAN
    INNER JOIN DSEDAC.ART ART ON TRIM(LAC.CODIGOARTICULO) = TRIM(ART.CODIGOARTICULO)
    WHERE CAC.ANODOCUMENTO = 2026 AND CAC.MESDOCUMENTO = 4
      AND TRIM(CAC.CODIGOCLIENTEFACTURA) LIKE '43%'
      AND CAC.NUMEROFACTURA > 0
      AND TRIM(ART.CODIGOFAMILIA) IN (${F})
      AND TRIM(LAC.CLASELINEA) IN (${C})
    GROUP BY TRIM(LAC.TIPOVENTA)
  `);
  let cc3=0, sc3=0; r3.forEach(x=>{if(x.TV==='CC')cc3=x.CAJAS;if(x.TV==='SC')sc3=x.CAJAS;});
  console.log('Con ABS: CC=' + cc3 + ', SC=' + sc3);

  console.log('\n=== RESUMEN ===');
  console.log('Mi actual (COALESCE): CC=' + cc1 + ', SC=' + sc1);
  console.log('Con ABS: CC=' + cc3 + ', SC=' + sc3);
  console.log('Objetivo: CC=3865, SC=11');
  console.log('Diferencia ABS: CC=' + (3865-cc3) + ', SC=' + (11-sc3));

  process.exit(0);
})();