const db = require('../app/config/odbcConfig');

async function checkDateAndVC() {
    await db.initialize();

    try {
        const tiposFull = await db.query(`
      SELECT TRIM(LAC.TIPOVENTA) AS TIPO, SUM(CANTIDADENVASES) AS CAJAS
      FROM DSEDAC.CAC CAC
      INNER JOIN DSEDAC.LAC LAC ON LAC.SUBEMPRESAALBARAN = CAC.SUBEMPRESAALBARAN AND LAC.EJERCICIOALBARAN = CAC.EJERCICIOALBARAN AND LAC.SERIEALBARAN = CAC.SERIEALBARAN AND LAC.TERMINALALBARAN = CAC.TERMINALALBARAN AND LAC.NUMEROALBARAN = CAC.NUMEROALBARAN
      INNER JOIN DSEDAC.ART ART ON TRIM(LAC.CODIGOARTICULO) = TRIM(ART.CODIGOARTICULO)
      WHERE CAC.EJERCICIOALBARAN = 2026 
        AND TRIM(CAC.CODIGOCLIENTEFACTURA) NOT LIKE '44%'
        AND TRIM(ART.CODIGOFAMILIA) IN ('700', '701', '702', '704', '705', '706')
        AND TRIM(LAC.CLASELINEA) IN ('AB', 'RG', 'VT')
      GROUP BY TRIM(LAC.TIPOVENTA)
    `);
        console.log('--- Tipos de Venta (Enero-Dic 2026) Familias 700-706 ---');
        tiposFull.forEach(t => console.log(`${t.TIPO}: ${t.CAJAS} cajas`));

        const fechas = await db.query(`
      SELECT CAC.ANODOCUMENTO, CAC.MESDOCUMENTO, CAC.EJERCICIOALBARAN, COALESCE(SUM(LAC.CANTIDADENVASES), 0) AS CAJAS
      FROM DSEDAC.CAC CAC
      INNER JOIN DSEDAC.LAC LAC ON LAC.SUBEMPRESAALBARAN = CAC.SUBEMPRESAALBARAN AND LAC.EJERCICIOALBARAN = CAC.EJERCICIOALBARAN AND LAC.SERIEALBARAN = CAC.SERIEALBARAN AND LAC.TERMINALALBARAN = CAC.TERMINALALBARAN AND LAC.NUMEROALBARAN = CAC.NUMEROALBARAN
      INNER JOIN DSEDAC.ART ART ON TRIM(LAC.CODIGOARTICULO) = TRIM(ART.CODIGOARTICULO)
      WHERE 
        ((CAC.ANODOCUMENTO = 2025 AND CAC.MESDOCUMENTO = 12) OR 
         (CAC.ANODOCUMENTO = 2026 AND CAC.MESDOCUMENTO IN (1, 2)) OR
         (CAC.EJERCICIOALBARAN = 2026 AND CAC.MESDOCUMENTO IN (1, 2, 12)))
        AND TRIM(CAC.CODIGOCLIENTEFACTURA) NOT LIKE '44%'
        AND TRIM(ART.CODIGOFAMILIA) IN ('700', '701', '702', '704', '705', '706')
        AND TRIM(LAC.CLASELINEA) IN ('AB', 'RG', 'VT')
      GROUP BY CAC.ANODOCUMENTO, CAC.MESDOCUMENTO, CAC.EJERCICIOALBARAN
      ORDER BY CAC.ANODOCUMENTO, CAC.MESDOCUMENTO
    `);
        console.log('\n--- Sumas por Fechas ---');
        fechas.forEach(f => console.log(`Año: ${f.ANODOCUMENTO}, Mes: ${f.MESDOCUMENTO}, Ejercicio: ${f.EJERCICIOALBARAN} -> ${f.CAJAS} cajas`));

    } catch (e) {
        console.log('ERROR:', e.message);
    }

    await db.close();
    process.exit(0);
}

checkDateAndVC().catch(e => { console.error(e.message); process.exit(1); });
