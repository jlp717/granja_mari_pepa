/**
 * Diagnóstico de cajas PANAMAR
 * Ejecutar: node scripts/diagnostico-cajas-panamar.js
 */
const db = require('../app/config/odbcConfig');

const EJERCICIO = 2026;
const FAMILIAS = "'701', '702', '703', '704', '705'";
const CLASES_LINEA = "'AB', 'RG', 'VT'";

async function run() {
  try {
    await db.initialize();
    console.log('Conectado a DB. Ejecutando diagnósticos...\n');

    // 1) Columnas TIPO* y CLASE* en LAC
    console.log('=== 1) Columnas TIPO* y CLASE* en LAC ===');
    const cols = await db.query(`
      SELECT COLUMN_NAME, DATA_TYPE, LENGTH, COLUMN_TEXT
      FROM QSYS2.SYSCOLUMNS
      WHERE TABLE_SCHEMA = 'DSEDAC' AND TABLE_NAME = 'LAC'
        AND (COLUMN_NAME LIKE '%TIPO%' OR COLUMN_NAME LIKE '%CLASE%')
      ORDER BY COLUMN_NAME
    `);
    console.table(cols);

    // 2) Valores distintos de CLASELINEA en LAC (para docs PANAMAR)
    console.log('\n=== 2) Valores distintos de CLASELINEA en LAC (PANAMAR) ===');
    const clases = await db.query(`
      SELECT TRIM(LAC.CLASELINEA) AS CLASE, COUNT(*) AS LINEAS,
             COALESCE(SUM(LAC.CANTIDADENVASES), 0) AS CAJAS
      FROM DSEDAC.CAC CAC
      INNER JOIN DSEDAC.LAC LAC
        ON LAC.SUBEMPRESAALBARAN = CAC.SUBEMPRESAALBARAN
        AND LAC.EJERCICIOALBARAN = CAC.EJERCICIOALBARAN
        AND LAC.SERIEALBARAN = CAC.SERIEALBARAN
        AND LAC.TERMINALALBARAN = CAC.TERMINALALBARAN
        AND LAC.NUMEROALBARAN = CAC.NUMEROALBARAN
      INNER JOIN DSEDAC.ART ART ON TRIM(LAC.CODIGOARTICULO) = TRIM(ART.CODIGOARTICULO)
      WHERE CAC.EJERCICIOALBARAN = ${EJERCICIO}
        AND TRIM(CAC.CODIGOCLIENTEFACTURA) LIKE '4300%'
        AND TRIM(ART.CODIGOFAMILIA) IN (${FAMILIAS})
        AND LAC.IMPORTEVENTA <> 0
      GROUP BY TRIM(LAC.CLASELINEA)
      ORDER BY TRIM(LAC.CLASELINEA)
    `);
    console.table(clases);

    // 3) Cajas por mes CON filtro CLASELINEA IN (AB, RG, VT) y IMPORTEVENTA <> 0
    console.log('\n=== 3) Cajas por mes CON filtro CLASELINEA + IMPORTEVENTA <> 0 ===');
    const cajasConFiltro = await db.query(`
      SELECT
        CAC.MESDOCUMENTO AS MES,
        COUNT(DISTINCT CAC.NUMEROALBARAN || '-' || CAC.SERIEALBARAN || '-' || CAC.TERMINALALBARAN || '-' || CAC.EJERCICIOALBARAN) AS DOCS,
        COALESCE(SUM(LAC.CANTIDADENVASES), 0) AS CAJAS_ENVASES,
        COALESCE(SUM(LAC.CANTIDADUNIDADES), 0) AS UNIDADES,
        COUNT(*) AS LINEAS
      FROM DSEDAC.CAC CAC
      INNER JOIN DSEDAC.LAC LAC
        ON LAC.SUBEMPRESAALBARAN = CAC.SUBEMPRESAALBARAN
        AND LAC.EJERCICIOALBARAN = CAC.EJERCICIOALBARAN
        AND LAC.SERIEALBARAN = CAC.SERIEALBARAN
        AND LAC.TERMINALALBARAN = CAC.TERMINALALBARAN
        AND LAC.NUMEROALBARAN = CAC.NUMEROALBARAN
      INNER JOIN DSEDAC.ART ART ON TRIM(LAC.CODIGOARTICULO) = TRIM(ART.CODIGOARTICULO)
      WHERE CAC.EJERCICIOALBARAN = ${EJERCICIO}
        AND TRIM(CAC.CODIGOCLIENTEFACTURA) LIKE '4300%'
        AND TRIM(ART.CODIGOFAMILIA) IN (${FAMILIAS})
        AND LAC.IMPORTEVENTA <> 0
        AND TRIM(LAC.CLASELINEA) IN (${CLASES_LINEA})
      GROUP BY CAC.MESDOCUMENTO
      ORDER BY CAC.MESDOCUMENTO
    `);
    console.table(cajasConFiltro);

    // 4) Cajas por mes SIN filtro CLASELINEA (para comparar)
    console.log('\n=== 4) Cajas por mes SIN filtro CLASELINEA (para comparar) ===');
    const cajasSinFiltro = await db.query(`
      SELECT
        CAC.MESDOCUMENTO AS MES,
        COALESCE(SUM(LAC.CANTIDADENVASES), 0) AS CAJAS_ENVASES,
        COUNT(*) AS LINEAS
      FROM DSEDAC.CAC CAC
      INNER JOIN DSEDAC.LAC LAC
        ON LAC.SUBEMPRESAALBARAN = CAC.SUBEMPRESAALBARAN
        AND LAC.EJERCICIOALBARAN = CAC.EJERCICIOALBARAN
        AND LAC.SERIEALBARAN = CAC.SERIEALBARAN
        AND LAC.TERMINALALBARAN = CAC.TERMINALALBARAN
        AND LAC.NUMEROALBARAN = CAC.NUMEROALBARAN
      INNER JOIN DSEDAC.ART ART ON TRIM(LAC.CODIGOARTICULO) = TRIM(ART.CODIGOARTICULO)
      WHERE CAC.EJERCICIOALBARAN = ${EJERCICIO}
        AND TRIM(CAC.CODIGOCLIENTEFACTURA) LIKE '4300%'
        AND TRIM(ART.CODIGOFAMILIA) IN (${FAMILIAS})
        AND LAC.IMPORTEVENTA <> 0
      GROUP BY CAC.MESDOCUMENTO
      ORDER BY CAC.MESDOCUMENTO
    `);
    console.table(cajasSinFiltro);

    // 5) CC/SC desglose por mes CON CLASELINEA filter
    console.log('\n=== 5) Desglose CC/SC por mes (con CLASELINEA filter) ===');
    const ccsc = await db.query(`
      SELECT
        CAC.MESDOCUMENTO AS MES,
        TRIM(LAC.TIPOVENTA) AS TIPO,
        COALESCE(SUM(LAC.CANTIDADENVASES), 0) AS CAJAS
      FROM DSEDAC.CAC CAC
      INNER JOIN DSEDAC.LAC LAC
        ON LAC.SUBEMPRESAALBARAN = CAC.SUBEMPRESAALBARAN
        AND LAC.EJERCICIOALBARAN = CAC.EJERCICIOALBARAN
        AND LAC.SERIEALBARAN = CAC.SERIEALBARAN
        AND LAC.TERMINALALBARAN = CAC.TERMINALALBARAN
        AND LAC.NUMEROALBARAN = CAC.NUMEROALBARAN
      INNER JOIN DSEDAC.ART ART ON TRIM(LAC.CODIGOARTICULO) = TRIM(ART.CODIGOARTICULO)
      WHERE CAC.EJERCICIOALBARAN = ${EJERCICIO}
        AND TRIM(CAC.CODIGOCLIENTEFACTURA) LIKE '4300%'
        AND TRIM(ART.CODIGOFAMILIA) IN (${FAMILIAS})
        AND LAC.IMPORTEVENTA <> 0
        AND TRIM(LAC.CLASELINEA) IN (${CLASES_LINEA})
      GROUP BY CAC.MESDOCUMENTO, TRIM(LAC.TIPOVENTA)
      ORDER BY CAC.MESDOCUMENTO, TRIM(LAC.TIPOVENTA)
    `);
    console.table(ccsc);

    // 6) Verificar duplicados en ARA tarifa 85
    console.log('\n=== 6) Duplicados en ARA tarifa 85 ===');
    const dupes = await db.query(`
      SELECT TRIM(ARA.CODIGOARTICULO) AS ARTICULO, COUNT(*) AS FILAS
      FROM DSEDAC.ARA ARA
      WHERE ARA.CODIGOTARIFA = 85
      GROUP BY TRIM(ARA.CODIGOARTICULO)
      HAVING COUNT(*) > 1
    `);
    if (dupes.length === 0) {
      console.log('Sin duplicados en ARA tarifa 85 - OK');
    } else {
      console.table(dupes);
    }

    // 7) Resumen total Enero con todos los filtros
    console.log('\n=== 7) RESUMEN ENERO - con CLASELINEA IN (AB,RG,VT) ===');
    const enero = await db.query(`
      SELECT
        COUNT(DISTINCT CAC.NUMEROALBARAN || '-' || CAC.SERIEALBARAN || '-' || CAC.TERMINALALBARAN || '-' || CAC.EJERCICIOALBARAN) AS DOCUMENTOS,
        COALESCE(SUM(LAC.CANTIDADENVASES), 0) AS TOTAL_CAJAS,
        COALESCE(SUM(CASE WHEN TRIM(LAC.TIPOVENTA) = 'CC' THEN LAC.CANTIDADENVASES ELSE 0 END), 0) AS CAJAS_CC,
        COALESCE(SUM(CASE WHEN TRIM(LAC.TIPOVENTA) = 'SC' THEN LAC.CANTIDADENVASES ELSE 0 END), 0) AS CAJAS_SC,
        COUNT(*) AS TOTAL_LINEAS
      FROM DSEDAC.CAC CAC
      INNER JOIN DSEDAC.LAC LAC
        ON LAC.SUBEMPRESAALBARAN = CAC.SUBEMPRESAALBARAN
        AND LAC.EJERCICIOALBARAN = CAC.EJERCICIOALBARAN
        AND LAC.SERIEALBARAN = CAC.SERIEALBARAN
        AND LAC.TERMINALALBARAN = CAC.TERMINALALBARAN
        AND LAC.NUMEROALBARAN = CAC.NUMEROALBARAN
      INNER JOIN DSEDAC.ART ART ON TRIM(LAC.CODIGOARTICULO) = TRIM(ART.CODIGOARTICULO)
      WHERE CAC.EJERCICIOALBARAN = ${EJERCICIO}
        AND CAC.MESDOCUMENTO = 1
        AND TRIM(CAC.CODIGOCLIENTEFACTURA) LIKE '4300%'
        AND TRIM(ART.CODIGOFAMILIA) IN (${FAMILIAS})
        AND LAC.IMPORTEVENTA <> 0
        AND TRIM(LAC.CLASELINEA) IN (${CLASES_LINEA})
    `);
    console.table(enero);
    console.log(`\n>>> ESPERADO POR JEFE: 3623 cajas en Enero <<<`);
    console.log(`>>> RESULTADO QUERY:   ${enero[0]?.TOTAL_CAJAS} cajas en Enero <<<\n`);

    await db.close();
    process.exit(0);
  } catch (err) {
    console.error('ERROR:', err.message);
    process.exit(1);
  }
}

run();
